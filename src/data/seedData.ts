// Helper to generate realistic past 30 days of attendance records for employees
function generatePast30DaysAttendance(): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  const today = new Date();

  // Define realistic shift profiles for employees
  const employeeShiftConfigs = [
    { empId: 'emp_01', name: 'Danish Khan', code: 'EMP-1001', dept: 'Engineering', locId: 'loc_hq', locName: 'Silicon Oasis Headquarters', baseIn: '08:52', baseOut: '17:35', baseHours: 8.7 },
    { empId: 'emp_02', name: 'Sarah Mitchell (Manager)', code: 'MGR-2001', dept: 'Engineering & Product', locId: 'loc_hq', locName: 'Silicon Oasis Headquarters', baseIn: '08:35', baseOut: '17:40', baseHours: 9.1 },
    { empId: 'emp_03', name: 'Marcus Vance', code: 'EMP-1045', dept: 'Product Design', locId: 'loc_downtown', locName: 'Downtown Innovation Center', baseIn: '09:05', baseOut: '17:20', baseHours: 8.2 },
    { empId: 'emp_04', name: 'Priya Sharma', code: 'EMP-1089', dept: 'Human Resources', locId: 'loc_hq', locName: 'Silicon Oasis Headquarters', baseIn: '08:48', baseOut: '17:15', baseHours: 8.4 },
    { empId: 'emp_07', name: 'David Chen', code: 'EMP-1155', dept: 'Enterprise Sales', locId: 'loc_westside', locName: 'Westside Business Park', baseIn: '08:58', baseOut: '17:30', baseHours: 8.5 },
  ];

  let idCounter = 1;

  for (let daysAgo = 29; daysAgo >= 0; daysAgo--) {
    const d = new Date(today);
    d.setDate(today.getDate() - daysAgo);
    const dateStr = d.toISOString().split('T')[0];
    const isWeekend = d.getDay() === 0 || d.getDay() === 6; // Sun or Sat

    // Skip weekends for regular shifts
    if (isWeekend) continue;

    employeeShiftConfigs.forEach((cfg, empIdx) => {
      const isToday = daysAgo === 0;

      // Add small natural jitter to punch times
      const jitterMinsIn = ((daysAgo * 3 + empIdx * 7) % 25) - 10; // -10 to +14 mins
      const jitterMinsOut = ((daysAgo * 5 + empIdx * 3) % 35) - 10;
      
      const inHour = 8;
      const inMinute = Math.max(30, Math.min(58, 50 + jitterMinsIn));
      const inSecond = (daysAgo * 7 + 11) % 60;
      const checkInTime = `${String(inHour).padStart(2, '0')}:${String(inMinute).padStart(2, '0')}:${String(inSecond).padStart(2, '0')}`;

      let checkOutTime: string | undefined = undefined;
      let totalHours = 8.0;
      let status: 'on_time' | 'late' | 'half_day' | 'completed' | 'active' = 'completed';

      if (isToday) {
        // Today is active shift
        status = 'active';
        totalHours = 0;
      } else {
        const outHour = 17;
        const outMinute = Math.max(10, Math.min(55, 30 + jitterMinsOut));
        const outSecond = (daysAgo * 13 + 24) % 60;
        checkOutTime = `${String(outHour).padStart(2, '0')}:${String(outMinute).padStart(2, '0')}:${String(outSecond).padStart(2, '0')}`;
        
        // Calculate total hours
        const inDecimal = inHour + inMinute / 60;
        const outDecimal = outHour + outMinute / 60;
        totalHours = Math.round((outDecimal - inDecimal) * 10) / 10;

        // Occasional late or permission day for realistic variation
        if (daysAgo === 4 && cfg.empId === 'emp_01') {
          status = 'late';
        } else if (daysAgo === 12 && cfg.empId === 'emp_01') {
          totalHours = 4.5;
          status = 'half_day';
          checkOutTime = '13:30:00';
        } else if (inMinute > 55) {
          status = 'late';
        } else {
          status = 'on_time';
        }
      }

      records.push({
        id: `att_${String(idCounter++).padStart(3, '0')}`,
        employeeId: cfg.empId,
        employeeName: cfg.name,
        employeeCode: cfg.code,
        department: cfg.dept,
        date: dateStr,
        checkInTime,
        checkOutTime,
        officeLocationId: cfg.locId,
        officeLocationName: cfg.locName,
        checkInCoords: {
          latitude: 37.789210 + (empIdx * 0.0001),
          longitude: -122.401380 + (empIdx * 0.0001),
          accuracy: 6 + (daysAgo % 8),
        },
        checkOutCoords: checkOutTime ? {
          latitude: 37.789190 + (empIdx * 0.0001),
          longitude: -122.401350 + (empIdx * 0.0001),
          accuracy: 5 + (daysAgo % 7),
        } : undefined,
        distanceToOfficeMeters: 12 + ((daysAgo * 3 + empIdx) % 30),
        isGeofenceValid: true,
        status,
        totalHoursWorked: isToday ? undefined : totalHours,
        deviceInfo: empIdx % 2 === 0 ? 'iPhone 15 Pro / Safari Mobile GPS' : 'Android Pixel 8 / Chrome GPS',
        notes: isToday ? 'Arrived on time for sprint planning standup.' : undefined,
      });
    });
  }

  // Sort descending by date
  return records.sort((a, b) => b.date.localeCompare(a.date));
}

